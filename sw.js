// Сайт не использует service worker и не регистрирует его ни на одной странице.
// Этот файл существует только для того, чтобы снять регистрации, оставшиеся в браузерах
// посетителей от прежней версии сайта.
//
// Что было: sw.js удалён вместе со старой версией, но location для .js отдавал на любой
// несуществующий путь index.html с кодом 200 и Content-Type: text/html. Браузер такой ответ
// при проверке обновления отвергает по MIME-типу, поэтому старый воркер не обновлялся и не
// снимался — он продолжал перехватывать все запросы к сайту и отдавать свой устаревший кэш,
// а каждая проверка тянула 155 КБ HTML вместо скрипта.
//
// Теперь браузер получает валидный скрипт, ставит его вместо старого воркера, и тот сам себя
// удаляет. Фолбэк для .js убран в nginx.conf, так что повториться это не может.
//
// Файл можно удалить, когда в логах пропадут запросы к /sw.js (проверять по access-логу
// контейнера randomhost) — до тех пор он нужен тем, кто ещё не заходил после этой правки.

self.addEventListener('install', () => {
  // Не ждём закрытия вкладок со старым воркером: смысл этой сборки в том, чтобы заменить его
  // как можно раньше.
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    // Снести кэши старого воркера обязательно: unregister() их не трогает, и без этого
    // storage браузера остаётся занят копией сайта, которая уже никому не нужна.
    const names = await caches.keys();
    await Promise.all(names.map((name) => caches.delete(name)));

    // Перехватить управление у старого воркера немедленно. Здесь это безопасно: обработчика
    // fetch у этой сборки нет, запросы идут в сеть напрямую.
    await self.clients.claim();

    await self.registration.unregister();
  })());
});

